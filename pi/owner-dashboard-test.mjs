import assert from 'node:assert/strict';
import fs from 'node:fs';

const html=fs.readFileSync('owner-dashboard.html','utf8');
const js=fs.readFileSync('owner-dashboard.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const history=JSON.parse(fs.readFileSync('pi/engineering-history.json','utf8'));
const app=fs.readFileSync('app.js','utf8');
const store=fs.readFileSync('worker/src/session-store.mjs','utf8');

assert.ok(html.includes('Private owner monitor'),'public_owner_lock_notice_missing');
assert.ok(html.includes('Owner Control Center'),'owner_control_center_heading_missing');
assert.ok(html.includes('Krishna / Team'),'owner_team_panel_missing');
assert.ok(html.includes('7-Day Engineering Summary'),'owner_history_summary_missing');
assert.ok(html.includes('Lock dashboard'),'owner_logout_control_missing');
assert.ok(html.includes('disabled on the public PI website'),'public_owner_monitor_not_locked');
assert.equal(js.includes('api.github.com'),false,'public_owner_monitor_must_not_fetch_telemetry');
assert.match(js,/sessionStorage\.getItem\(OWNER_SESSION_KEY\)/,'owner_dashboard_must_use_tab_scoped_owner_session');
assert.match(js,/Authorization.*Bearer/,'owner_dashboard_must_require_bearer_session');
assert.match(js,/\/api\/owner\/dashboard/,'owner_dashboard_must_use_canonical_owner_api');
assert.equal(js.includes('PI_OWNER_DASHBOARD_TOKEN'),false,'owner_dashboard_must_not_create_parallel_auth_secret');
assert.equal(js.includes('/.netlify/functions/owner-status'),false,'owner_dashboard_must_not_use_parallel_netlify_auth_path');
assert.match(js,/cache:"no-store"/,'owner_dashboard_fetch_must_not_cache_private_state');
assert.match(js,/referrerPolicy:"no-referrer"/,'owner_dashboard_must_not_leak_referrer');
assert.match(js,/\/api\/owner\/logout/,'owner_dashboard_must_support_secure_logout');
assert.match(js,/renderHistory\(d\.history\)/,'owner_dashboard_must_render_verified_history');
assert.match(js,/renderTeam\(d\.team\)/,'owner_dashboard_must_render_verified_team_state');
assert.match(index,/id="ownerAccess"[^>]*>Owner Login<\/button>/,'owner_login_must_be_clearly_visible');
assert.match(index,/aria-haspopup="dialog"/,'owner_login_must_expose_dialog_semantics');
assert.match(index,/aria-controls="ownerDialog"/,'owner_login_must_identify_controlled_dialog');
assert.match(index,/id="ownerDialog"[^>]*aria-labelledby="ownerLoginTitle"/,'owner_dialog_must_have_accessible_name');
assert.match(index,/id="ownerLoginTitle">Owner Login<\/h2>/,'owner_dialog_title_must_be_explicit');
assert.equal(index.includes('id="ownerDashboard"'),false,'public_pi_must_not_link_owner_dashboard');
assert.equal(app.includes('pi-v1-owner-conversation'),false,'owner_conversation_must_not_persist_in_browser_local_storage');
assert.equal(app.includes('pi-v1-owner-draft'),false,'owner_draft_must_not_persist_in_browser_local_storage');
assert.match(app,/sessionStorage\.setItem\(OWNER_SESSION_KEY/,'owner_session_must_be_tab_scoped');
assert.match(store,/secureEqual\(payload\?\.secret, env\.PI_OWNER_TOKEN\)/,'owner_secret_must_be_verified_server_side');
assert.match(store,/owner_login_rate_check/,'owner_login_must_be_rate_limited');
assert.match(store,/OWNER_SESSION_TTL_MS = 12 \* 60 \* 60 \* 1000/,'owner_session_ttl_must_remain_bounded');
assert.match(store,/origin && origin !== allowedOrigin/,'owner_api_must_reject_wrong_origin');
assert.match(store,/workspace_clear/,'owner_workspace_must_support_server_side_deletion');
assert.match(store,/'cache-control': 'no-store'/,'owner_api_must_disable_response_caching');

assert.equal(history.verifiedDay1.date,'2026-09-15','wrong_verified_day1');
assert.equal(history.verifiedDay1.commit,'20d9c93d34e2e58e569415e479144d6ab1374dfd','wrong_day1_commit');
assert.equal(history.scope,'public-engineering-evidence-only','history_scope_must_exclude_private_telemetry');
assert.equal(history.privacy.containsPrivateTelemetry,false,'private_telemetry_must_not_be_committed');
assert.ok(Array.isArray(history.daily) && history.daily.length >= 7,'day1_history_missing_daily_rows');
assert.equal(history.daily[0].date,'2026-09-15','history_must_start_at_day1');
assert.ok(history.totals.commits >= 683,'verified_commit_history_regressed');
assert.ok(history.totals.workflowRuns >= 5572,'verified_workflow_history_regressed');
assert.ok(history.privacy.excluded.includes('revenue'),'revenue_must_stay_out_of_public_history');
assert.ok(history.privacy.excluded.includes('secrets'),'secrets_must_stay_out_of_public_history');
assert.equal(history.backfill?.status,'complete-for-supported-public-evidence','day1_backfill_contract_incomplete');
assert.equal(history.backfill?.startsAt,'2026-09-15','day1_backfill_start_regressed');
assert.equal(history.backfill?.unavailableFields?.additions,null,'unknown_additions_must_not_be_faked');
assert.equal(history.backfill?.unavailableFields?.deletions,null,'unknown_deletions_must_not_be_faked');
assert.equal(history.backfill?.unavailableFields?.filesChanged,null,'unknown_files_changed_must_not_be_faked');
assert.ok(history.daily.every((row)=>Object.hasOwn(row,'additions') && Object.hasOwn(row,'deletions') && Object.hasOwn(row,'filesChanged')),'daily_code_volume_unknowns_must_be_explicit');
assert.equal(history.daily.at(-1).snapshotPartialDay,true,'current_snapshot_must_be_marked_partial');

console.log('PI owner privacy, visible Owner Login, and Day 1 history contract tests passed.');
